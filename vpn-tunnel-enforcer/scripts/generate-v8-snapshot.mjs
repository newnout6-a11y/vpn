#!/usr/bin/env node
// scripts/generate-v8-snapshot.mjs
//
// Generates a V8 startup snapshot for the Electron MAIN process.
//
// A V8 snapshot pre-compiles JS and serializes the resulting heap state
// into a binary blob (snapshot_blob.bin / v8_context_snapshot.bin). At
// runtime Electron deserializes the blob instead of parsing and
// compiling the JS from scratch, saving ~200-500 ms of module-load time
// at startup.
//
// ── OPT-IN & SAFE ──────────────────────────────────────────────────
//   mksnapshot is NOT bundled with the `electron` npm package. If it is
//   not installed the script prints install instructions and exits 0 so
//   the build/dist chain is never broken. The runtime loader
//   (src/main/snapshotBootstrap.ts) is a complete no-op when no snapshot
//   is active, so the app works identically with or without a snapshot.
//
// ── HOW TO ENABLE ──────────────────────────────────────────────────
//   1.  npm i -D @electron/mksnapshot
//       (downloads the mksnapshot binary matching your Electron version)
//   2.  npm run build:snapshot
//   3.  Blobs are written to resources/snapshot/ and bundled via the
//       electron-builder extraResources entry.
//   4.  For Electron to actually LOAD the custom snapshot at startup,
//       the .bin files must replace the defaults in the Electron dist
//       directory (next to electron.exe). The script prints the exact
//       paths when it succeeds.
//
// ── WHEN TO REGENERATE ─────────────────────────────────────────────
//   • A snapshot'd dependency is upgraded or added.
//   • Electron itself is upgraded — the blob is V8/Electron-version
//     specific. A blob built for Electron 42 will NOT load under 43.
//
// ── CAVEAT ─────────────────────────────────────────────────────────
//   V8 snapshots are notoriously finicky. The snapshot input requires
//   Node modules in a bare V8 context that lacks `require`. This script
//   makes a best effort; if mksnapshot fails it warns and exits 0.
//   The app is fully functional without the snapshot.

import { spawnSync } from 'child_process'
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync
} from 'fs'
import { dirname, join, resolve } from 'path'
import { fileURLToPath } from 'url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const isWin = process.platform === 'win32'
const snapshotOutDir = join(root, 'resources', 'snapshot')
const workDir = join(root, '.snapshot-tmp')

// The heaviest externalized main-process dependencies. These are the
// `dependencies` in package.json that electron-vite's
// externalizeDepsPlugin leaves as runtime `require()` calls. Built-in
// Node modules (electron, child_process, dns, net, path, util, os, fs,
// http, https ...) are already part of Electron's default snapshot and
// are intentionally NOT listed here.
const SNAPSHOT_MODULES = ['axios', 'electron-store', 'socks', 'sudo-prompt']

function log(msg) {
  console.log(`[build:snapshot] ${msg}`)
}
function warn(msg) {
  console.warn(`[build:snapshot] WARN: ${msg}`)
}

// ── Locate the mksnapshot binary ───────────────────────────────────
//
// @electron/mksnapshot installs a .bin shim. On Windows that's a .cmd
// wrapper; on POSIX it's a symlink. We also check the package's own bin
// directory and an explicit MKSNAPSHOT_PATH env override.
function findMksnapshot() {
  const names = isWin
    ? ['mksnapshot.cmd', 'mksnapshot.ps1', 'mksnapshot']
    : ['mksnapshot']
  const dirs = [
    join(root, 'node_modules', '.bin'),
    join(root, 'node_modules', '@electron', 'mksnapshot', 'bin')
  ]
  for (const dir of dirs) {
    for (const name of names) {
      const candidate = join(dir, name)
      if (existsSync(candidate)) return candidate
    }
  }
  if (process.env.MKSNAPSHOT_PATH && existsSync(process.env.MKSNAPSHOT_PATH)) {
    return process.env.MKSNAPSHOT_PATH
  }
  return null
}

// ── Generate the snapshot input script ─────────────────────────────
//
// This file is fed to mksnapshot. It requires each heavy dependency so
// its parsed/compiled code + object graph is captured in the snapshot.
// It also exposes the results on a `snapshotResult` global so the
// runtime loader (snapshotBootstrap.ts) can serve them without
// re-parsing.
function writeSnapshotInput(targetPath) {
  const safeName = (m) => `__snap_${m.replace(/[^a-zA-Z0-9]/g, '_')}`
  const requires = SNAPSHOT_MODULES.map(
    (m) => `globalThis.${safeName(m)} = require('${m}');`
  ).join('\n')
  const expose = SNAPSHOT_MODULES.map(
    (m) => `  '${m}': globalThis.${safeName(m)},`
  ).join('\n')
  const content = `// AUTO-GENERATED by scripts/generate-v8-snapshot.mjs — do not edit.
// Fed to mksnapshot to capture the heaviest main-process dependencies
// in a serialized V8 heap blob. Regenerate when deps change or Electron
// is upgraded (the blob is V8-version-specific).
"use strict";
${requires}
// Expose captured modules so snapshotBootstrap.ts can serve them via
// the snapshotResult global without re-parsing/re-compiling.
globalThis.snapshotResult = globalThis.snapshotResult || {};
globalThis.snapshotResult.modules = {
${expose}
};
`
  writeFileSync(targetPath, content, 'utf8')
}

// ── Main ───────────────────────────────────────────────────────────

const mksnapshot = findMksnapshot()
if (!mksnapshot) {
  warn('mksnapshot not found.')
  warn('Install it with:  npm i -D @electron/mksnapshot')
  warn('The app works normally without a snapshot — skipping generation.')
  process.exit(0)
}

log(`found mksnapshot: ${mksnapshot}`)

// Log the Electron version — the blob is version-specific and will NOT
// load under a different Electron/V8 version.
try {
  const electronPkg = JSON.parse(
    readFileSync(join(root, 'node_modules', 'electron', 'package.json'), 'utf8')
  )
  log(`Electron ${electronPkg.version} — snapshot blob is V8-version-specific`)
} catch {
  // non-critical — continue without the version banner
}

// Prepare a clean work directory so stale blobs from a previous run
// don't get copied.
rmSync(workDir, { recursive: true, force: true })
mkdirSync(workDir, { recursive: true })

// Write the snapshot input script.
const inputFile = join(workDir, 'snapshot-input.js')
writeSnapshotInput(inputFile)
log(`wrote snapshot input → ${inputFile}`)

// Run mksnapshot. We pass the input file and let mksnapshot write its
// default output(s) into the work directory. Different mksnapshot
// versions accept different flags; we try the common invocation and
// copy any .bin blobs that appear afterward.
log('running mksnapshot...')
const result = spawnSync(
  mksnapshot,
  [inputFile, '--startup_blob', 'snapshot_blob.bin'],
  { cwd: workDir, stdio: 'inherit', shell: isWin }
)

if (result.status !== 0) {
  warn(`mksnapshot exited with code ${result.status}.`)
  warn('V8 snapshots are finicky — this is non-fatal.')
  warn('The app will work normally without a snapshot.')
  rmSync(workDir, { recursive: true, force: true })
  process.exit(0)
}

// Collect generated .bin blobs.
mkdirSync(snapshotOutDir, { recursive: true })
const blobs = readdirSync(workDir).filter((f) => f.endsWith('.bin'))
if (blobs.length === 0) {
  warn('mksnapshot succeeded but produced no .bin blobs.')
  rmSync(workDir, { recursive: true, force: true })
  process.exit(0)
}

for (const blob of blobs) {
  copyFileSync(join(workDir, blob), join(snapshotOutDir, blob))
  log(`copied ${blob} → resources/snapshot/${blob}`)
}

rmSync(workDir, { recursive: true, force: true })

log(`done — ${blobs.length} blob(s) in resources/snapshot/.`)
log('Next steps:')
log('  • The blobs must replace the defaults in node_modules/electron/dist/')
log('    for Electron to load them at startup.')
log('  • Regenerate when dependencies change or Electron is upgraded.')
